/**
 * Bundles api-src/*.ts into self-contained CommonJS files at their deployed api/ paths:
 *   api-src/agent-execute.ts        -> api/agent-execute.js
 *   api-src/agent-execute-health.ts -> api/agent-execute/health.js
 *   api-src/site-capture.ts         -> api/site-capture.js
 *
 * Why: Vercel's Node Functions builder does not bundle a multi-file TypeScript entry or resolve
 * the tsconfig "@/*" path alias at runtime — it transpiles each file individually and ships the
 * import graph as separate files, which then fails to resolve "@/…" imports in production. Source
 * files use "@/…" aliases (the app's convention, unchanged); esbuild inlines everything here so
 * the deployed function has zero first-party imports left to resolve at runtime. npm packages
 * (e.g. @supabase/supabase-js) stay external — Vercel installs node_modules for the function.
 *
 * Run: npm run build:vercel-functions (wired into vercel.json's buildCommand — never edit the
 * generated api/*.js files by hand, they are overwritten on every build).
 */
import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import path from "node:path";

const entries = [
  { entryPoints: ["api-src/agent-execute.ts"], outfile: "api/agent-execute.js" },
  { entryPoints: ["api-src/agent-execute-health.ts"], outfile: "api/agent-execute/health.js" },
  { entryPoints: ["api-src/site-capture.ts"], outfile: "api/site-capture.js" },
];

for (const { entryPoints, outfile } of entries) {
  mkdirSync(path.dirname(outfile), { recursive: true });
  await build({
    entryPoints,
    outfile,
    bundle: true,
    format: "cjs",
    platform: "node",
    target: "node20",
    legalComments: "none",
    packages: "external", // only bundle first-party "@/…"/relative source; npm packages stay real requires
    banner: { js: "// Generated by scripts/bundle-vercel-functions.mjs — do not edit." },
    alias: { "@": path.resolve("src") },
  });
  console.log(`Bundled ${outfile}`);
}
