/**
 * Bundles scripts/benchmark/run-stage.ts into one plain-Node file: dist/benchmark/run-stage.js
 *
 * Same pattern as scripts/bundle-mcp-server.mjs (esbuild, "@/" alias resolved to src/, no other
 * source file changes needed). Scratch operational tooling for the CTOS-004A Part Q benchmark
 * exercise, not a committed CT-OS feature — not wired into package.json.
 */
import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import path from "node:path";

mkdirSync("dist/benchmark", { recursive: true });
await build({
  entryPoints: ["scripts/benchmark/run-stage.ts"],
  outfile: "dist/benchmark/run-stage.js",
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node18",
  legalComments: "none",
  banner: { js: "// Generated by scripts/bundle-benchmark-runner.mjs - scratch tooling, Part Q benchmark. Run with: node dist/benchmark/run-stage.js <in.json> <out.json>" },
  alias: { "@": path.resolve("src") },
});
console.log("Bundled dist/benchmark/run-stage.js");
