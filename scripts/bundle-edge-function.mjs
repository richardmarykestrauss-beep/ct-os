/**
 * Bundles the agent-execute Edge Function into one Deno-ready file:
 *   supabase/functions/agent-execute/dist/index.js
 * Source files use "@/…" aliases and extension-less imports (the app's convention); the deployed
 * function must not depend on them, so esbuild inlines our code and rewrites npm packages to
 * Deno `npm:` specifiers. Deploy with: supabase functions deploy agent-execute --import-map none
 * (or point the CLI at the dist entry — see docs/EXECUTION-GATEWAY.md).
 */
import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import path from "node:path";

const NPM = { zod: "npm:zod@4", "@supabase/supabase-js": "npm:@supabase/supabase-js@2" };
mkdirSync("supabase/functions/agent-execute/dist", { recursive: true });
await build({
  entryPoints: ["supabase/functions/agent-execute/index.ts"],
  outfile: "supabase/functions/agent-execute/dist/index.js",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "esnext",
  legalComments: "none",
  banner: { js: "// Generated by scripts/bundle-edge-function.mjs — do not edit. Deno Edge Function bundle for CT-OS agent-execute." },
  alias: { "@": path.resolve("src") },
  plugins: [
    {
      name: "deno-npm-specifiers",
      setup(b) {
        b.onResolve({ filter: /^(zod|@supabase\/supabase-js)$/ }, (args) => ({ path: NPM[args.path], external: true }));
      },
    },
  ],
});
console.log("Bundled supabase/functions/agent-execute/dist/index.js");
