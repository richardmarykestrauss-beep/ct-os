/**
 * Bundles the local MCP bridge into one plain-Node file: dist/mcp-server/index.js
 *
 * Same pattern as scripts/bundle-edge-function.mjs (esbuild, "@/" alias resolved, no other source
 * file changes needed to add a new bundle target) but simpler: this runs under plain Node with
 * node_modules available, not Deno, so nothing needs to be rewritten to an `npm:` specifier.
 * `@modelcontextprotocol/sdk` is marked external and resolved normally from node_modules at run
 * time, instead of being inlined, since it is a large package with its own native/optional deps
 * (this mirrors how the SDK's own examples recommend bundling a server).
 */
import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import path from "node:path";

mkdirSync("dist/mcp-server", { recursive: true });
await build({
  entryPoints: ["src/mcp/server.ts"],
  outfile: "dist/mcp-server/index.js",
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node18",
  legalComments: "none",
  banner: { js: "// Generated by scripts/bundle-mcp-server.mjs — do not edit. Local CT-OS MCP bridge (CTOS-004). Run with: node dist/mcp-server/index.js" },
  alias: { "@": path.resolve("src") },
  external: ["@modelcontextprotocol/sdk", "@modelcontextprotocol/sdk/*"],
});
console.log("Bundled dist/mcp-server/index.js");
